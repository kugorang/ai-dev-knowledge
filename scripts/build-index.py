class Slugger:
    """GitHub-compatible heading anchors (same rules as github-slugger)."""

    def __init__(self):
        self.seen = {}

    @staticmethod
    def base(text):
        kept = []
        for ch in text.lower():
            cat = unicodedata.category(ch)
            if ch in " -" or cat[0] in "LMN" or cat == "Pc":
                kept.append(ch)
        return "".join(kept).replace(" ", "-")

    def slug(self, text):
        original = self.base(text)
        result = original
        while result in self.seen:
            self.seen[original] += 1
            result = f"{original}-{self.seen[original]}"
        self.seen[result] = 0
        return result


def plain_heading(text):
    """Heading text as GitHub renders it (links and code spans unwrapped)."""
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return text.replace("`", "").strip()


def entry_files():
    monthly = sorted(ENTRIES_DIR.glob("[0-9][0-9][0-9][0-9]-[0-9][0-9].md"))
    files = [(p, 2) for p in monthly]
    bookmarks = ENTRIES_DIR / "bookmarks.md"
    if bookmarks.exists():
        files.append((bookmarks, 3))
    return files


def parse_file(path, level):
    slugger = Slugger()
    entries = []
    current = None
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = HEADING_RE.match(line)
        if heading:
            anchor = slugger.slug(plain_heading(heading.group(2)))
            current = None
            if len(heading.group(1)) == level:
                current = {"title": heading.group(2).strip(), "anchor": anchor,
                           "file": path.name}
                entries.append(current)
            continue
        field = FIELD_RE.match(line)
        if field and current is not None:
            current.setdefault(field.group(1), field.group(2).strip())
    return [e for e in entries if "도구" in e and "요약" in e and "날짜" in e]


def date_key(raw):
    found = DATE_RE.findall(raw)
    if not found:
        return ("", "")
    return max((d, t) for d, t in found)


def first_sentence(text):
    match = SENTENCE_RE.match(text)
    return match.group(1) if match else text


def tool_slugs(raw):
    tokens = [t.strip().lower() for t in raw.split(",")]
    has_codex = any("codex" in t for t in tokens)
    found = set()
    for t in tokens:
        if "claude code" in t:
            found.add("claude-code")
        if "codex" in t:
            found.add("codex")
        if "cursor" in t:
            found.add("cursor")
        if "grok" in t:
            found.add("grok-bot")
        if "chatgpt" in t or (("openai" in t or "gpt" in t) and not has_codex):
            found.add("chatgpt")
    return found


def theme_slugs(entry):
    haystack = f"{entry['title']} {entry['요약']}".lower()
    return {th["slug"] for th in THEMES
            if any(re.search(k, haystack) for k in th["keywords"])}


def link_text(title):
    return title.replace("[", "\\[").replace("]", "\\]")


def render_topic(topic, items):
    lines = [MARKER, "", f"# {topic['title']}", "",
             topic["ko"], "", topic["en"], "",
             f"항목 {len(items)}개, 최신순 / {len(items)} entries, newest first.",
             ""]
    for e in items:
        lines.append(f"- [{link_text(e['title'])}](../entries/{e['file']}"
                     f"#{e['anchor']}) ({e['date']}): "
                     f"{first_sentence(e['요약'])}")
    return "\n".join(lines) + "\n"


def render_index(groups, total):
    lines = [MARKER, "", "# 주제별 색인 (Topic Index)", "",
             "도구와 주제별로 `entries/`의 항목을 모은 색인입니다. "
             "한 항목이 여러 페이지에 나올 수 있습니다.", "",
             "Indexes of `entries/` grouped by tool and by theme. "
             "One entry can appear on several pages.", "",
             f"전체 항목 / Total entries: {total}", ""]
    for heading, topics in groups:
        lines += [f"## {heading}", ""]
        for topic, count in topics:
            lines.append(f"- [{topic['title']}]({topic['slug']}.md): {count}")
        lines.append("")
    return "\n".join(lines)


def build():
    entries = []
    for path, level in entry_files():
        entries.extend(parse_file(path, level))
    for order, e in enumerate(entries):
        e["order"] = order
        e["sort"] = date_key(e["날짜"])
        e["date"] = e["sort"][0] or e["날짜"]
    entries.sort(key=lambda e: (e["sort"], e["order"]), reverse=True)

    outputs = {}
    groups = []
    for heading, topics, matcher in (
            ("도구별 (By tool)", TOOLS, lambda e: tool_slugs(e["도구"])),
            ("주제별 (By theme)", THEMES, theme_slugs)):
        counted = []
        for topic in topics:
            items = [e for e in entries if topic["slug"] in matcher(e)]
            outputs[f"{topic['slug']}.md"] = render_topic(topic, items)
            counted.append((topic, len(items)))
        groups.append((heading, counted))
    outputs["README.md"] = render_index(groups, len(entries))
    return outputs


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, content in build().items():
        path = TOPICS_DIR / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(name)
        if not check:
            TOPICS_DIR.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8")
    verb = "out of date" if check else "updated"
    print(f"{verb}: {', '.join(stale) if stale else 'nothing'}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
